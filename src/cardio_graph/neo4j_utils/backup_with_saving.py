"""
This script demonstrates the "Full Export/Import" approach for creating complete
snapshots of your Neo4j database using the APOC library.

---
What is the Full Export/Import (APOC) approach?
---
This method exports the entire database (or a selection) into a portable Cypher
script. This script contains all the `CREATE` statements for nodes, relationships,
indexes, and constraints. It's a reliable way to create a full, point-in-time
backup of your graph.

It's ideal for:
- Creating major versioned backups (e.g., 'v1.0', 'v2.0').
- Migrating the database to another server.
- Disaster recovery.

This method is slower than in-graph versioning for quick experiments but provides
a more complete and isolated backup.

---
How to use this approach in your project:
---
1.  **Export the Graph (Backup):**
    Run the `export_graph_to_file` function. This will connect to the database,
    call the `apoc.export.cypher.all` procedure, and stream the resulting Cypher
    commands into a local file (e.g., 'my_graph_backup.cypher').

2.  **Restore the Graph:**
    To restore the graph from a backup file, you have two main options:

    a) **Full Restore (Destructive):**
       First, completely clear the database by running `MATCH (n) DETACH DELETE n`.
       Then, run the `restore_graph_from_file` function, pointing it to your
       backup file. This will rebuild the graph from scratch.

    b) **Partial Restore (Non-Destructive):**
       If you want to add the data from the backup to the existing graph without
       deleting anything, simply run `restore_graph_from_file` on the live
       database. Note that this may create duplicate data if the nodes/relationships
       already exist.

This script provides functions to test the full export and restore cycle.
"""

import os

